// Função comun no JavaScript

function somar(a,b) {
    return a + b
}

function subtrair(a,b) {
    return a - b 
}

function multiplicacao(a,b) {
    return a * b
}

function Divisao(a,b) {
    return a / b
}

const soma = somar(2,3)
const subtracao = subtrair(2,3)
const multiplica = multiplicacao(2,3)
const dividi = Divisao(10 , 10)

// console.log(`Soma: ${soma}`)

console.log("SOMA: ", soma)
console.log("Subtração: ", subtracao)
console.log("Multiplicação: ", multiplica)
