// Operadores lógicos

condicao_a = 1 < 2
condicao_b = 10 < 2

//  AND SO VAI SER VERDADEIRO SER FOR 2 VERDADEIROS ( V AND V = V ) , O RESTO E FALSO
console.log(" - AND  - ")
console.log(condicao_a && condicao_b)

//  Ser for Verdadeiro  = Falso  ou Falso  = Verdadeiro.

console.log("\n  - NOT - ")
console.log(condicao_a && !condicao_b)

//  OR SO VAI SER FALSO SER FOR 2 FALSO (F  OR F = F) , O RESTO E VERDADEIRO
console.log("\n - OR -")
console.log(condicao_a || condicao_b)
